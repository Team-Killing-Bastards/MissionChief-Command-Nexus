import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'..');
const source=fs.readFileSync(path.join(root,'nexus-real-locations.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
assert.equal(manifest.version,'3.0.43.189');
assert.ok(source.includes("box.className='nx-real-popup'"),'marker click must render the rich Nexus location card');
assert.ok(source.includes("details.className='nx-real-build'"),'location card must contain a collapsible Build section');
for(const label of ['Building Type','Dispatch Center','Starting Vehicle','Multi Build — same type'])assert.ok(source.includes(label),`missing build control ${label}`);
assert.ok(source.includes("panel.id='nx-realism-master-panel'"),'Multi Build master panel must be pinned in the map container');
assert.ok(source.includes("batch.set(masterKey,item)"),'first selected location must become the master selection');
assert.ok(source.includes("if(!compatible(item))"),'active Multi Build must reject incompatible service locations');
assert.ok(source.includes("batch.delete(k)"),'changing type / clearing must be able to remove non-master selections');
assert.ok(source.includes("Create ${batch.size} Building"),'master create action must show selected batch count');
assert.ok(source.includes("await buildOne(item,config)"),'batch creation must run verified per-location builds');
assert.ok(source.includes("No retry was sent"),'uncertain build outcome must fail closed without duplicate retry');
assert.ok(source.includes('fetchVerificationBuildings()'),'build verification must compare authoritative MissionChief building feeds');
assert.ok(source.includes("distanceMeters(item,b)<350"),'build verification must require a geographically matching result');
assert.ok(source.includes("builtKeys.add(itemKey(item))"),'verified builds must gain explicit marker state');
assert.ok(source.includes("Google Maps"),'rich card must offer Google Maps');
assert.ok(source.includes("OpenStreetMap"),'rich card must offer OpenStreetMap');
console.log('PASS: 3.0.43.151 provides rich Realism location cards and single-building-type Multi Build with verified per-location results.');
