import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source=fs.readFileSync(new URL('../nexus-runtime.js',import.meta.url),'utf8');
const parent=vm.createContext({});
const owner=vm.runInContext('globalThis',parent);
const worker=vm.createContext({owner});
vm.runInContext('owner.__NEXUS_DISPATCH_CAPTURE__ = { attempted: 8, accepted: 6, lastAt: 123, lastError: "", lastMissionId: "42" }',worker);
const old=owner.__NEXUS_DISPATCH_CAPTURE__;
assert.equal(Object.getPrototypeOf(old),vm.runInContext('Object.prototype',worker),'old record retains worker prototype');
const start=source.indexOf('    function getNexusDispatchCaptureHealth(');
const end=source.indexOf('    function captureNexusDispatchAction(',start);
vm.runInContext(source.slice(start,end),worker);
const health=vm.runInContext('getNexusDispatchCaptureHealth(owner)',worker);
assert.equal(Object.getPrototypeOf(health),null,'no worker prototype chain');
assert.notEqual(health,old);
assert.equal(health.attempted,8);assert.equal(health.accepted,6);assert.equal(health.lastMissionId,'42');
assert.equal(vm.runInContext('getNexusDispatchCaptureHealth(owner)',worker),health);
delete owner.__NEXUS_DISPATCH_CAPTURE__;
const fresh=vm.runInContext('getNexusDispatchCaptureHealth(owner)',worker);
assert.equal(Object.getPrototypeOf(fresh),null);assert.equal(fresh.attempted,0);
assert.match(source,/const health = getNexusDispatchCaptureHealth\(owner\)/);
console.log('PASS: reproduced worker prototype retention; migrated and fresh health records are prototype-free and preserve counters.');
