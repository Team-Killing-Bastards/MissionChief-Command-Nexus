import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here=path.dirname(fileURLToPath(import.meta.url)),root=path.resolve(here,'..');
const source=fs.readFileSync(path.join(root,'nexus-real-locations.js'),'utf8');
const manifest=JSON.parse(fs.readFileSync(path.join(root,'manifest.json'),'utf8'));
assert.equal(manifest.version,'3.0.43.189');
assert.ok(manifest.version_name.startsWith('3.0.43.189 '),'version_name must match packaged version');
assert.ok(source.includes('function responseBuildingId(url)'),'must use POST redirect URL as strong build evidence');
assert.ok(source.includes('for(let i=0;i<24;i++)'),'verification must allow MissionChief/API propagation time');
assert.ok(source.includes('return hasCoords?distanceMeters(item,b)<350:sameCaption(buildingCaptionOf(b),caption)'),'new station must be close to the requested location, or have an exact caption when coordinates are absent');
assert.ok(source.includes('sameCaption(buildingCaptionOf(b),caption)'),'caption evidence must be used when available');
assert.ok(source.includes('if(e?.uncertain){stopped=true'),'multi build must stop on an uncertain outcome');
assert.ok(source.includes('updateMarkerVisual(item);'),'successful builds should update marker state without rebuilding the whole layer');
const runBuild=source.slice(source.indexOf('async function runBuild('),source.indexOf('function syncToggleButtons',source.indexOf('async function runBuild(')));
assert.ok(!runBuild.includes('render();'),'single-build completion must not clear/recreate the marker layer and close its popup');
assert.ok(source.includes('No retry was sent'),'uncertain builds must remain fail-closed');
console.log('PASS: 3.0.43.189 keeps single-build popups open, strengthens build verification, and stops Multi Build safely on uncertain outcomes.');
